/* ------------------------------ CSV ------------------------------ */

function csvCell(v: string | number | null | undefined): string {
  const s = v === null || v === undefined ? '' : String(v)
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}

/** CDM 时间线 CSV（表头前为 # 注释元信息 + 免责声明；BOM 保证 Excel 中文不乱码） */
export function buildTimelineCsv(ctx: ExportEventCtx): string {
  const { event, t } = ctx
  const rows: string[] = []
  rows.push(`# ${t('exp.title')}: ${objName(event.nameA, event.noradA)} x ${objName(event.nameB, event.noradB)}`)
  rows.push(`# ${t('exp.eventKey')}: ${event.key}`)
  rows.push(`# TCA: ${fmtWhen(event.tca)} UTC`)
  rows.push(`# ${t('exp.generatedAt')}: ${fmtWhen(ctx.generatedAt)} UTC`)
  if (ctx.exportedBy) rows.push(`# ${t('exp.exportedBy')}: ${ctx.exportedBy}`)
  rows.push(`# ${disclaimer(ctx)}`)
  rows.push('')
  rows.push(
    [
      'cdm_id',
      'creation_date_utc',
      'originator',
      'tca_utc',
      'miss_distance_km',
      'rel_speed_km_per_s',
      'collision_probability',
      'hard_body_radius_m',
      'source'
    ].join(',')
  )
  for (const c of ctx.cdms) {
    rows.push(
      [
        csvCell(c.cdm_id ?? String(c.id)),
        csvCell(c.creation_date || ''),
        csvCell(c.originator || ''),
        csvCell(c.tca),
        csvCell(c.miss_distance_km),
        csvCell(c.rel_speed_km_per_s),
        csvCell(c.collision_probability),
        csvCell(c.hard_body_radius_m),
        csvCell(c.source)
      ].join(',')
    )
  }
  return `\uFEFF${rows.join('\r\n')}\r\n`
}

/* ------------------------------ 下载 ------------------------------ */

/** 触发浏览器下载（Blob + 临时 a[download]） */
export function downloadText(filename: string, text: string, mime: string): void {
  const blob = new Blob([text], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

/** 导出文件基名：OSP-Conjunction-{A}x{B}-{TCA 紧凑}（ASCII，跨平台安全） */
export function exportBaseName(event: ConjunctionEvent): string {
  const tca = event.tca.slice(0, 16).replace(/[-:]/g, '') // 2026-11-04T12:30 → 20261104T1230
  return `OSP-Conjunction-${event.noradA}x${event.noradB}-${tca}`
}
