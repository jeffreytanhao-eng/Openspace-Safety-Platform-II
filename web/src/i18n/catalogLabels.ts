const DIGIT = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十']
const GRADE: Record<string, string> = { A: '甲', B: '乙', C: '丙', D: '丁', E: '戊', F: 'F' }

function zhInt(n: number): string {
  if (n <= 10) return DIGIT[n]
  if (n < 20) return '十' + (n % 10 ? DIGIT[n % 10] : '')
  if (n < 100) {
    const t = Math.floor(n / 10)
    const o = n % 10
    return DIGIT[t] + '十' + (o ? DIGIT[o] : '')
  }
  return String(n)
}

function hasCjk(s: string): boolean {
  return /[\u3400-\u9fff]/.test(s)
}

function pickZh(code: string | null | undefined, english: string | null | undefined, byCode: Record<string, string>): string | null {
  const c = (code || '').trim()
  if (c) {
    for (const part of c.split('/')) {
      const hit = byCode[part.trim()]
      if (hit) return hit
    }
  }
  const en = (english || '').trim()
  if (en && NAME_ZH[en]) return NAME_ZH[en]
  if (en && hasCjk(en)) return en
  return en || null
}

export function catalogOrgLabel(code: string | null | undefined, english: string | null | undefined, isZh: boolean): string | null {
  if (isZh) return pickZh(code, english, orgZh)
  const en = (english || '').trim()
  return en || null
}

