export function catalogCountryCode(code: string | null | undefined, english: string | null | undefined): string | null {
  const raw = (code || '').trim()
  const first = raw.split('/')[0].trim()
  if (first) {
    return COUNTRY_ALIAS[first] || first
  }
  const en = (english || '').trim()
  return COUNTRY_ALIAS[en] || null
}

export function catalogPurposeCodes(codes: string[] | null | undefined, english: string | null | undefined): string[] {
  const fromApi = (codes ?? []).map((c) => c.trim()).filter(Boolean)
  if (fromApi.length) return fromApi
  const en = (english || '').trim()
  if (!en) return []
  return en.split('/').map((part) => {
    const t = part.trim()
    return PURPOSE_FROM_EN[t] || t
  }).filter(Boolean)
}

function zhYz(rest: string): string {
  return rest.replace(/\/YZ-(\d+)([A-Z])?/gi, (_m, n: string, l?: string) => {
    return `/远征${zhInt(Number(n))}号${l || ''}`
  })
}

export function catalogVehicleLabel(raw: string | null | undefined, isZh: boolean): string | null {
  const s = (raw || '').trim()
  if (!s) return null
  const cz = s.match(/^Chang Zheng\s+(\d+)([A-Z])?(.*)$/i)
  if (cz) {
    const num = Number(cz[1])
    const letter = (cz[2] || '').toUpperCase()
    const rest = cz[3] || ''
    if (isZh) {
      const g = letter ? GRADE[letter] || letter : ''
      return `长征${zhInt(num)}号${g}${zhYz(rest)}`
    }
    return `Long March ${cz[1]}${letter}${rest}`
  }
  if (isZh) {
    if (VEHICLE_ZH[s]) return VEHICLE_ZH[s]
    // prefix: "Kuaizhou 1A", "Soyuz-2-1a"
    const keys = Object.keys(VEHICLE_ZH).sort((a, b) => b.length - a.length)
    for (const k of keys) {
      if (s === k || s.startsWith(k + ' ') || s.startsWith(k + '-') || s.startsWith(k + '/')) {
        return VEHICLE_ZH[k] + s.slice(k.length)
      }
    }
  }
  return s
}

